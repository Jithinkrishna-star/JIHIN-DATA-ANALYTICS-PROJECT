#18.Find pairs of different product models that share the exact same price point by joining the table to itself using table aliases

SELECT a.`Product Code` AS Product_1, 
       b.`Product Code` AS Product_2, 
       a.Brand, 
       a.Price
FROM mobile_sales_data a
JOIN mobile_sales_data b ON a.Price = b.Price 
     AND a.`Product Code` < b.`Product Code`
