#19.Combine the top 5 highest-revenue transactions from the 'North' region and the top 5 from the 'South' region into a single unified comparative report

(SELECT 'North Top Sales' AS Region_Segment, `Product Code`, Brand, (Price * `Quantity Sold`) AS Revenue
 FROM mobile_sales_data
 WHERE Region = 'North'
 ORDER BY Revenue DESC
 LIMIT 5)
UNION ALL
(SELECT 'South Top Sales' AS Region_Segment, `Product Code`, Brand, (Price * `Quantity Sold`) AS Revenue
 FROM mobile_sales_data
 WHERE Region = 'South'
 ORDER BY Revenue DESC
