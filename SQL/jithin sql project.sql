# 11.Join the main sales table with a brand-average CTE to find products priced higher than their own brand's average

WITH BrandAvg AS (
    SELECT Brand, AVG(Price) AS Avg_Price 
    FROM mobile_sales_data 
    GROUP BY Brand
)
SELECT m.`Product Code`, m.Brand, m.Price, b.Avg_Price 
FROM mobile_sales_data m 
JOIN BrandAvg b ON m.Brand = b.Brand 
WHERE m.Price > b.Avg_Price 
LIMIT 50;

# 12.Find brands whose total calculated revenue exceeds 1,000,000 by filtering aggregated group results using the HAVING clause

