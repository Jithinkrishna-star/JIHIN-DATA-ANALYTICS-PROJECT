#17.Pivot your brand data to calculate total revenue generated in the 'North' region versus the 'South' region side-by-side in a single summary row per brand

SELECT Brand,
       SUM(CASE WHEN Region = 'North' THEN Price * `Quantity Sold` ELSE 0 END) AS North_Revenue,
