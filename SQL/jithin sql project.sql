#14.Use a CTE to pre-compute brand average prices and join back to isolate items above average without timeout errors

WITH BrandAvg AS (
    SELECT Brand, AVG(Price) AS Avg_P 
    FROM mobile_sales_data 
    GROUP BY Brand
)
SELECT m.`Product Code`, m.Brand, m.Price, b.Avg_P 
FROM mobile_sales_data m 
JOIN BrandAvg b ON m.Brand = b.Brand 
WHERE m.Price > b.Avg_P 
LIMIT 50;

